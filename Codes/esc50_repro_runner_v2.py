"""ESC-50 ACDNet / XNOR reproduction runner (Python 3.7+, PyTorch 1.8+).

Place this file in the root of mohaimenz/pruning-vs-xnor and run from the
repository root. Reuses datasets/esc50/wav20.npz prepared previously.

The runner uses online BC-learning augmentation and genuine held-out folds.

v2: Adds resumable full-training checkpoints. For faithful LR scheduling,
start a new 2000-epoch run; do NOT try to resume a 200-epoch run as 2000.
Mini/Micro checkpoint files supply ARCHITECTURE only; pretrained weights are
intentionally not loaded, to avoid train/test leakage across ESC-50 folds.

Models: acdnet, mini, micro, xacdnet, xmini (QMicro is a separate PTQ step).
This is a training/evaluation runner, not structured channel-pruning itself.
"""
from __future__ import print_function

import argparse
import csv
import os
import random
import sys
import time

import numpy as np
import torch

from audio.nets import models
from audio.resources import esc_subsets
from audio.resources import utils as U
from common.binop_lib import BinOp

INPUT_LENGTH = 30225
SAMPLE_RATE = 20000
N_CROPS = 10


def parse_args():
    p = argparse.ArgumentParser(description='ESC-50 fold-safe reproduction')
    p.add_argument('--data-root', default='datasets/esc50')
    p.add_argument('--model', choices=['acdnet', 'mini', 'micro', 'xacdnet', 'xmini'], default='mini')
    p.add_argument('--classes', type=int, nargs='+', default=[50], choices=[10, 20, 30, 40, 50])
    p.add_argument('--folds', type=int, nargs='+', default=[1], choices=[1, 2, 3, 4, 5])
    p.add_argument('--epochs', type=int, default=1)
    p.add_argument('--batch-size', type=int, default=64)
    p.add_argument('--steps-per-epoch', type=int, default=0,
                   help='0 = floor(train sample count / batch size); small integer = smoke test')
    p.add_argument('--eval-every', type=int, default=1)
    p.add_argument('--eval-sample-batch', type=int, default=2,
                   help='Number of distinct recordings per validation forward batch (10 crops each)')
    p.add_argument('--device', choices=['auto', 'cpu', 'cuda'], default='auto')
    p.add_argument('--seed', type=int, default=42)
    p.add_argument('--output', default='experiments/esc50')
    p.add_argument('--save-every', type=int, default=10,
                   help='Save full resumable state every N completed epochs')
    p.add_argument('--resume', action='store_true',
                   help='Resume only from a state checkpoint generated by this script')
    return p.parse_args()


def get_subset(n_classes):
    if n_classes == 50:
        return list(range(50))
    return list(getattr(esc_subsets, 'esc{}'.format(n_classes)))


def load_folds(path):
    if not os.path.isfile(path):
        raise IOError('Missing {}. Use the wav20.npz built yesterday.'.format(path))
    with np.load(path, allow_pickle=True) as archive:
        folds = {}
        for fold in range(1, 6):
            obj = archive['fold{}'.format(fold)].item()
            folds[fold] = list(zip(obj['sounds'], [int(x) for x in obj['labels']]))
    print('Loaded ESC-50: {}'.format(', '.join('fold{}={}'.format(k, len(v)) for k, v in sorted(folds.items()))))
    return folds


def select_fold(fold_data, test_fold, classes):
    mapping = {original: new for new, original in enumerate(classes)}
    train = []
    test = []
    for fold, records in fold_data.items():
        destination = test if fold == test_fold else train
        for sound, label in records:
            if label in mapping:
                destination.append((sound, mapping[label]))
    expected_train = 32 * len(classes)
    expected_test = 8 * len(classes)
    if len(train) != expected_train or len(test) != expected_test:
        raise ValueError('Unexpected ESC-50 split: training={} (expected {}), test={} (expected {})'.format(
            len(train), expected_train, len(test), expected_test))
    return train, test


def get_config(model_name):
    if model_name in ['acdnet', 'xacdnet']:
        return None
    fname = 'audio/models/{}_acdnet.pt'.format(model_name[1:] if model_name == 'xmini' else model_name)
    if not os.path.isfile(fname):
        raise IOError('Missing channel-config checkpoint: {}'.format(fname))
    # Important: only take the layer/channel counts, NOT these checkpoint weights.
    payload = torch.load(fname, map_location='cpu')
    if not isinstance(payload, dict) or 'config' not in payload:
        raise ValueError('Checkpoint does not contain config: {}'.format(fname))
    return payload['config']


def create_model(model_name, n_classes, device):
    config = get_config(model_name)
    is_binary = model_name.startswith('x')
    factory = models.GetBINACDNetModel if is_binary else models.GetACDNetModel
    model = factory(INPUT_LENGTH, n_classes, SAMPLE_RATE, config).to(device)
    binop = BinOp(model) if is_binary else None
    return model, binop, config


def set_seed(seed):
    random.seed(seed)
    np.random.seed(seed)
    torch.manual_seed(seed)
    if torch.cuda.is_available():
        torch.cuda.manual_seed_all(seed)


class BCLearningBatches(object):
    """Reproduce audio/resources/train_generator.py mixing logic on demand."""
    def __init__(self, records, n_classes):
        self.records = records
        self.n_classes = n_classes
        self.labels = np.eye(n_classes, dtype=np.float32)
        self.scale = U.random_scale(1.25)
        self.pad = U.padding(INPUT_LENGTH // 2)
        self.crop = U.random_crop(INPUT_LENGTH)
        self.norm = U.normalize(32768.0)
        self.gain = U.random_gain(6)

    def augment(self, audio):
        return self.norm(self.crop(self.pad(self.scale(audio))))

    def batch(self, batch_size, device):
        x = np.empty((batch_size, 1, 1, INPUT_LENGTH), dtype=np.float32)
        y = np.empty((batch_size, self.n_classes), dtype=np.float32)
        for i in range(batch_size):
            a, label_a = random.choice(self.records)
            b, label_b = random.choice(self.records)
            while label_a == label_b:
                b, label_b = random.choice(self.records)
            a = self.augment(a)
            b = self.augment(b)
            r = random.random()
            mixed = U.mix(a, b, np.array(r), SAMPLE_RATE).astype(np.float32)
            x[i, 0, 0, :] = self.gain(mixed).astype(np.float32)
            y[i, :] = self.labels[label_a] * r + self.labels[label_b] * (1 - r)
        return torch.from_numpy(x).to(device), torch.from_numpy(y).to(device)


def validation_crops(audio):
    # Same normalization/crop order as original val_generator.py.
    padded = U.padding(INPUT_LENGTH // 2)(audio)
    normalized = U.normalize(32768.0)(padded)
    return U.multi_crop(INPUT_LENGTH, N_CROPS)(normalized).astype(np.float32)


def evaluate(model, binop, records, n_classes, device, sample_batch):
    model.eval()
    if binop is not None:
        binop.binarization()
    correct = 0
    total_loss = 0.0
    try:
        with torch.no_grad():
            for idx in range(0, len(records), sample_batch):
                group = records[idx: idx + sample_batch]
                stacked = np.stack([validation_crops(audio) for audio, _ in group], axis=0)
                tensor = torch.from_numpy(stacked.reshape(-1, 1, 1, INPUT_LENGTH)).to(device)
                output = model(tensor).reshape(len(group), N_CROPS, n_classes).mean(dim=1)
                targets = torch.tensor([label for _, label in group], dtype=torch.long, device=device)
                correct += int((output.argmax(dim=1) == targets).sum().item())
                selected = output.gather(1, targets.view(-1, 1)).clamp(min=1e-8)
                total_loss += float((-selected.log()).sum().item())
    finally:
        if binop is not None:
            binop.restore()
        model.train()
    return (100.0 * correct / len(records), total_loss / len(records))


def learning_rate(epoch, max_epochs):
    # Mirrors the published repository's __get_lr, including 10-epoch warmup.
    decay = sum(epoch > max_epochs * fraction for fraction in [0.3, 0.6, 0.9])
    if epoch <= 10:
        decay = 1
    return 0.1 * (0.1 ** decay)


def append_csv(path, row, fields):
    exists = os.path.isfile(path)
    with open(path, 'a', newline='') as fp:
        writer = csv.DictWriter(fp, fieldnames=fields)
        if not exists:
            writer.writeheader()
        writer.writerow(row)


def load_local_checkpoint(path, map_location='cpu'):
    # Only load files this project created locally. Never unpickle unknown files.
    try:
        return torch.load(path, map_location=map_location, weights_only=False)
    except TypeError:  # older PyTorch
        return torch.load(path, map_location=map_location)


def save_atomic(payload, path):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    tmp = path + '.tmp'
    torch.save(payload, tmp)
    os.replace(tmp, path)


def capture_rng_state():
    state = {'python': random.getstate(),
             'numpy': np.random.get_state(),
             'torch': torch.get_rng_state()}
    if torch.cuda.is_available():
        state['cuda'] = torch.cuda.get_rng_state_all()
    return state


def restore_rng_state(state):
    random.setstate(state['python'])
    np.random.set_state(state['numpy'])
    torch.set_rng_state(state['torch'].cpu())
    if torch.cuda.is_available() and 'cuda' in state:
        torch.cuda.set_rng_state_all(state['cuda'])


def reconcile_history_for_resume(csv_path, target_model, n_classes, fold, last_epoch, fields):
    # A crash may leave history rows newer than the most recent state snapshot.
    if not os.path.isfile(csv_path):
        return
    with open(csv_path, 'r', newline='') as fp:
        rows = list(csv.DictReader(fp))
    kept = []
    removed = 0
    for row in rows:
        match = (row['model'] == target_model and int(row['classes']) == n_classes
                 and int(row['fold']) == fold)
        if match and int(row['epoch']) > last_epoch:
            removed += 1
        else:
            kept.append(row)
    if removed:
        tmp = csv_path + '.tmp'
        with open(tmp, 'w', newline='') as fp:
            writer = csv.DictWriter(fp, fieldnames=fields)
            writer.writeheader()
            writer.writerows(kept)
        os.replace(tmp, csv_path)
        print('Reconciled history: dropped {} rows after saved epoch {}'.format(removed, last_epoch))


def train_one(args, folds, n_classes, test_fold, device, csv_path):
    set_seed(args.seed)
    selected_classes = get_subset(n_classes)
    train, validation = select_fold(folds, test_fold, selected_classes)
    model, binop, config = create_model(args.model, n_classes, device)
    print('\n=== {} / {} classes / fold {} ==='.format(args.model, n_classes, test_fold), flush=True)
    print('Train={}  Validation={}  Device={}  Parameters={:,}'.format(
        len(train), len(validation), device, sum(p.numel() for p in model.parameters())), flush=True)
    is_binary = binop is not None
    if is_binary:
        optimizer = torch.optim.Adam(model.parameters(), lr=0.001, weight_decay=1e-4)
        scheduler = torch.optim.lr_scheduler.CosineAnnealingLR(optimizer, T_max=args.epochs)
    else:
        optimizer = torch.optim.SGD(model.parameters(), lr=0.1, weight_decay=5e-4,
                                    momentum=0.9, nesterov=True)
        scheduler = None
    loss_fn = torch.nn.KLDivLoss(reduction='batchmean')
    source = BCLearningBatches(train, n_classes)
    steps = args.steps_per_epoch or (len(train) // args.batch_size)
    if steps < 1:
        raise ValueError('steps-per-epoch must be >= 1')
    best_acc = -1.0
    best_path = os.path.join(args.output, 'checkpoints', '{}_c{}_fold{}.pt'.format(args.model, n_classes, test_fold))
    state_path = os.path.join(args.output, 'checkpoints', '{}_c{}_fold{}_trainstate.pt'.format(args.model, n_classes, test_fold))
    fields = ['model', 'classes', 'fold', 'epoch', 'train_accuracy', 'train_loss',
              'validation_accuracy', 'validation_loss', 'lr', 'seconds', 'steps', 'batch_size', 'seed']
    run_metadata = {'model': args.model, 'classes': n_classes, 'fold': test_fold,
                    'seed': args.seed, 'epochs': args.epochs, 'batch_size': args.batch_size,
                    'steps': steps, 'eval_every': args.eval_every}
    start_epoch = 1
    if args.resume:
        if not os.path.isfile(state_path):
            has_history = False
            if os.path.isfile(csv_path):
                with open(csv_path, 'r', newline='') as fp:
                    has_history = any(row['model'] == args.model
                                      and int(row['classes']) == n_classes
                                      and int(row['fold']) == test_fold
                                      for row in csv.DictReader(fp))
            if has_history:
                raise IOError('History exists but no trainstate checkpoint was found: {}'.format(state_path))
            print('No previous state for this fold; starting it from epoch 1.', flush=True)
        else:
            saved = load_local_checkpoint(state_path)
            if saved.get('metadata') != run_metadata:
                raise ValueError('Resume settings do not match saved run. Saved: {} | Current: {}'.format(
                    saved.get('metadata'), run_metadata))
            model.load_state_dict(saved['model_state'])
            optimizer.load_state_dict(saved['optimizer_state'])
            if scheduler is not None:
                scheduler.load_state_dict(saved['scheduler_state'])
            best_acc = float(saved['best_acc'])
            start_epoch = int(saved['epoch']) + 1
            restore_rng_state(saved['rng_state'])
            reconcile_history_for_resume(csv_path, args.model, n_classes, test_fold,
                                         start_epoch - 1, fields)
            print('Resuming {} class {} fold {} from epoch {} (best {:.2f}%)'.format(
                args.model, n_classes, test_fold, start_epoch, best_acc), flush=True)
    elif os.path.isfile(csv_path):
        with open(csv_path, 'r', newline='') as fp:
            for row in csv.DictReader(fp):
                if (row['model'] == args.model and int(row['classes']) == n_classes
                        and int(row['fold']) == test_fold):
                    raise ValueError('History exists for this run. Use a NEW --output directory '
                                     'or --resume (if a v2 trainstate checkpoint exists).')
    for epoch in range(start_epoch, args.epochs + 1):
        start = time.time()
        model.train()
        if not is_binary:
            lr = learning_rate(epoch, args.epochs)
            optimizer.param_groups[0]['lr'] = lr
        else:
            lr = optimizer.param_groups[0]['lr']
        correct_accum = 0.0
        loss_accum = 0.0
        for _ in range(steps):
            x, y = source.batch(args.batch_size, device)
            optimizer.zero_grad()
            if binop is not None:
                binop.binarization()
            outputs = model(x)
            loss = loss_fn(outputs.clamp(min=1e-8).log(), y)
            correct_accum += float((outputs.argmax(1) == y.argmax(1)).float().mean().item())
            loss_accum += float(loss.item())
            loss.backward()
            if binop is not None:
                binop.restore()
                binop.updateBinaryGradWeight()
            optimizer.step()
        if scheduler is not None:
            scheduler.step()
        val_acc, val_loss = float('nan'), float('nan')
        if epoch % args.eval_every == 0 or epoch == args.epochs:
            val_acc, val_loss = evaluate(model, binop, validation, n_classes, device,
                                         args.eval_sample_batch)
            if val_acc > best_acc:
                best_acc = val_acc
                torch.save({'weight': model.state_dict(), 'config': list(config) if config is not None else None,
                            'meta': {'model': args.model, 'classes': n_classes, 'fold': test_fold,
                                     'epoch': epoch, 'accuracy': val_acc, 'seed': args.seed}}, best_path)
        seconds = time.time() - start
        row = dict(model=args.model, classes=n_classes, fold=test_fold, epoch=epoch,
                   train_accuracy=round(correct_accum / steps * 100, 4),
                   train_loss=round(loss_accum / steps, 6),
                   validation_accuracy=round(val_acc, 4), validation_loss=round(val_loss, 6),
                   lr=lr, seconds=round(seconds, 2), steps=steps,
                   batch_size=args.batch_size, seed=args.seed)
        append_csv(csv_path, row, fields)
        if epoch % args.save_every == 0 or epoch == args.epochs:
            save_atomic({'epoch': epoch, 'metadata': run_metadata,
                         'model_state': model.state_dict(),
                         'optimizer_state': optimizer.state_dict(),
                         'scheduler_state': scheduler.state_dict() if scheduler is not None else None,
                         'best_acc': best_acc, 'rng_state': capture_rng_state()}, state_path)
        print('epoch {}/{} | train {:.2f}% loss {:.4f} | val {:.2f}% loss {:.4f} | {:.1f}s'.format(
            epoch, args.epochs, row['train_accuracy'], row['train_loss'],
            val_acc, val_loss, seconds), flush=True)
    return best_acc, best_path


def main():
    args = parse_args()
    if (args.epochs < 1 or args.batch_size < 1 or args.eval_every < 1
            or args.eval_sample_batch < 1 or args.save_every < 1):
        raise ValueError('Epochs, batch sizes, and eval-every must be positive')
    if args.device == 'cuda' and not torch.cuda.is_available():
        raise RuntimeError('CUDA selected but this venv has no CUDA-enabled PyTorch')
    device = torch.device('cuda' if (args.device == 'cuda' or (args.device == 'auto' and torch.cuda.is_available())) else 'cpu')
    os.makedirs(os.path.join(args.output, 'checkpoints'), exist_ok=True)
    csv_path = os.path.join(args.output, 'history.csv')
    wav_path = os.path.join(args.data_root, 'wav20.npz')
    print('Python {}'.format(sys.version.split()[0]))
    print('PyTorch {} | CUDA available: {}'.format(torch.__version__, torch.cuda.is_available()))
    print('Dataset: {}'.format(wav_path))
    folds = load_folds(wav_path)
    results = []
    for n_classes in args.classes:
        for fold in args.folds:
            best, ckpt = train_one(args, folds, n_classes, fold, device, csv_path)
            results.append((n_classes, fold, best, ckpt))
    print('\n=== BEST VALIDATION RESULTS ===')
    for n_classes, fold, accuracy, ckpt in results:
        print('{} classes, fold {}: {:.2f}% -> {}'.format(n_classes, fold, accuracy, ckpt))
    print('History CSV: {}'.format(csv_path))
    print('NOTE: Full trainstate checkpoints saved periodically; restart with identical args plus --resume.')
    print('NOTE: QMicro INT8 quantization and the channel-pruning procedure are separate steps.')
    if args.steps_per_epoch:
        print('NOTE: Steps were artificially limited. These are SMOKE TEST RESULTS, not paper-quality accuracies.')


if __name__ == '__main__':
    main()
